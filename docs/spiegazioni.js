// tutti i temi che compaiono in un testo, una volta sola e nell'ordine
const nomeSenzaNumero = (t) => String(t || '').replace(/\s*\(n\.\s*[^)]*\)/gi, ' ').replace(/\s+/g, ' ').trim();
export function substKeys(text) {
  const out = [];
  text = nomeSenzaNumero(text);
  for (const [re, k] of SUBST) if (re.test(text)) for (const x of [].concat(k)) if (!out.includes(x)) out.push(x);
  return out;
}
// il tema principale di un nome (il primo che corrisponde)
export function substKey(text) {
  text = nomeSenzaNumero(text);
  const hit = SUBST.find(([re]) => re.test(text));
  return hit ? [].concat(hit[1]) : [];
}
export function techKeys(text) {
  return TECH.filter(([re]) => re.test(text || '')).map(([, k]) => k);
}
